#!/bin/bash
# Builds ~/.config/aerospace/aerospace.toml from aerospace.base.toml plus a
# [gaps] table worked out per monitor, then reloads AeroSpace if it changed.
#
# AeroSpace only has static gaps, so this stands in for "smart gaps":
#   - one tiled window on a wide monitor: side gaps centre it
#   - two or more tiled windows: no side gaps, they share the whole screen
#   - narrow monitors (laptop): never padded
# Run by the callbacks in aerospace.base.toml.
#
#   smart-gaps.sh            regenerate, reload only if the result changed
#   smart-gaps.sh --force    regenerate and always reload, re-reading screen sizes
#   smart-gaps.sh --no-reload  just write the file (install.sh, AeroSpace not running)

# A lone window gets RATIO of the screen width, but never less than MIN_WIDTH
# points; screens no wider than MIN_WIDTH are left unpadded.
RATIO=0.75
MIN_WIDTH=1920
# Gap between windows on screens at least this wide.
INNER_GAP=10
INNER_GAP_MIN_SCREEN=2560

# AeroSpace runs callbacks with a minimal PATH, and /bin/bash is 3.2: no
# associative arrays below, and the aerospace CLI has to be found explicitly.
PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"

DIR="$HOME/.config/aerospace"
BASE="$DIR/aerospace.base.toml"
OUT="$DIR/aerospace.toml"
LOCK="${TMPDIR:-/tmp}/aerospace-smart-gaps.lock"
SCREENS="${TMPDIR:-/tmp}/aerospace-smart-gaps.screens"
DIRTY="$LOCK/dirty"

mode=${1:-}

# Callbacks fire in bursts. One run at a time; a run that finds the lock taken
# marks it dirty so the holder goes round once more with the latest state.
if ! mkdir "$LOCK" 2>/dev/null; then
    # Stale lock from a killed run: take it over after 10 seconds.
    if (($(date +%s) - $(stat -f %m "$LOCK" 2>/dev/null || date +%s) > 10)); then
        rm -rf "$LOCK" && mkdir "$LOCK" 2>/dev/null || exit 0
    else
        touch "$DIRTY" 2>/dev/null
        exit 0
    fi
fi
trap 'rm -rf "$LOCK"' EXIT

# Monitor name -> width in points, from AppKit (the names AeroSpace matches on).
# osascript is most of this script's run time, and every millisecond here is
# time the wrong gaps are on screen after a workspace switch, so the result is
# cached and only re-read when a monitor shows up that the cache doesn't know
# (or on --force, e.g. after changing a display's scaling).
screen_widths() {
    local monitors=$1 name
    if [[ $mode != --force && -f $SCREENS ]]; then
        while IFS= read -r name; do
            awk -F'\t' -v n="$name" '$1 == n { f = 1 } END { exit !f }' "$SCREENS" \
                || { rm -f "$SCREENS"; break; }
        done <<<"$monitors"
    else
        rm -f "$SCREENS"
    fi
    [[ -f $SCREENS ]] || osascript -l JavaScript -e 'ObjC.import("AppKit");
        $.NSScreen.screens.js.map(s => s.localizedName.js + "\t" + Math.round(s.frame.size.width)).join("\n")' \
        >"$SCREENS" 2>/dev/null
    cat "$SCREENS"
}

# Regex-escape a monitor name for AeroSpace's monitor patterns.
pattern() {
    printf '^%s$' "$(printf '%s' "$1" | sed 's/[][\.^$*+?(){}|/]/\\&/g')"
}

gaps_table() {
    local id name width count outer inner widths monitors
    local outer_rules="" inner_rules=""
    monitors=$(aerospace list-monitors --format '%{monitor-id}|%{monitor-name}' 2>/dev/null)
    widths=$(screen_widths "$(printf '%s\n' "$monitors" | cut -d'|' -f2-)")

    while IFS='|' read -r id name; do
        [[ -n $id ]] || continue # AeroSpace not running: no monitors listed
        width=$(printf '%s\n' "$widths" | awk -F'\t' -v n="$name" '$1 == n { print $2; exit }')
        width=${width:-0}
        # Tiled windows on screen. An accordion stacks its windows and shows one
        # at a time, so a workspace that is all accordion counts as one window.
        count=$(aerospace list-windows --monitor "$id" --workspace visible \
            --format '%{window-layout}' 2>/dev/null \
            | awk '$0 != "floating" { n++; if ($0 !~ /accordion$/) tiles = 1 }
                   END { print (n && !tiles) ? 1 : n + 0 }')

        outer=0
        if ((count <= 1 && width > MIN_WIDTH)); then
            outer=$(awk -v w="$width" -v r="$RATIO" -v m="$MIN_WIDTH" \
                'BEGIN { t = w * r; if (t < m) t = m; printf "%d", (w - t) / 2 }')
        fi
        inner=0
        ((width >= INNER_GAP_MIN_SCREEN)) && inner=$INNER_GAP

        outer_rules+="{ monitor.'$(pattern "$name")' = $outer }, "
        inner_rules+="{ monitor.'$(pattern "$name")' = $inner }, "
    done <<<"$monitors"

    cat <<EOF

# ---- generated by smart-gaps.sh; edit aerospace.base.toml instead ----
[gaps]
inner.horizontal = [${inner_rules}0]
inner.vertical = [${inner_rules}0]
outer.left = [${outer_rules}0]
outer.right = [${outer_rules}0]
outer.top = 0
outer.bottom = 0
EOF
}

while :; do
    rm -f "$DIRTY"
    new=$(cat "$BASE"; gaps_table)

    if [[ $new != "$(cat "$OUT" 2>/dev/null)" ]]; then
        # Replace rather than write through: OUT may still be the old stow link.
        tmp=$(mktemp "$DIR/.aerospace.toml.XXXXXX")
        printf '%s\n' "$new" >"$tmp" && mv -f "$tmp" "$OUT"
        [[ $mode != --no-reload ]] && aerospace reload-config --no-gui >/dev/null 2>&1
    elif [[ $mode == --force ]]; then
        aerospace reload-config >/dev/null 2>&1
    fi
    mode=${mode/--force/}

    [[ -e $DIRTY ]] || break
done
